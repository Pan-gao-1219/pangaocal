CATEGORIES = ['学科基础课程', '专业知识课程', '工作技能课程']

def extract_credits(text):
    result = {}
    for cat in CATEGORIES:
        positions = [m.start() for m in re.finditer(re.escape(cat), text)]
        if not positions:
            result[cat] = 0.0
            continue
        idx = positions[1] if len(positions) > 1 else positions[0]
        snippet = text[idx:idx+400]
        m = re.search(r'其中[：:]\s*必修\s*[\d.]+\s*学分[，,]\s*选修\s*([\d.]+)\s*学分', snippet)
        result[cat] = float(m.group(1)) if m else 0.0
    return result

def extract_courses(text, cat):
    positions = [m.start() for m in re.finditer(re.escape(cat), text)]
    if not positions:
        return []
    idx = positions[1] if len(positions) > 1 else positions[0]
    cat_idx = CATEGORIES.index(cat)
    end_idx = len(text)
    for nc in CATEGORIES[cat_idx+1:]:
        npos = [m.start() for m in re.finditer(re.escape(nc), text)]
        if len(npos) > 1:
            end_idx = min(end_idx, npos[1])
        elif npos:
            end_idx = min(end_idx, npos[0])
    section = text[idx:end_idx]
    markers = [m.start() for m in re.finditer(r'选修', section)]
    if not markers:
        return []
    elective_section = section[markers[-1]:]
    courses = re.findall(r'\d{12}\s+([^\n\d]{2,30}?)(?:\s+[\d.]+|\n|$)', elective_section)
    cleaned = []
    for c in courses:
        c = c.strip()
        if c and len(c) >= 2:
            cleaned.append(c)
    return cleaned

